def _env_bool(name, default=None):
    raw = os.environ.get(name)
    if raw is None:
        return default
    return raw.strip().lower() in {'1', 'true', 'yes'}

# DJANGO_USE_SQLITE accepts True/true/1/yes (case-insensitive). When it is
# not set at all, local development (DEBUG=True) defaults to SQLite instead
# of silently falling through to MySQL with a blank/wrong password — that
# silent fallback is what caused "Access denied for user 'root'@'localhost'
# (using password: NO)" after DJANGO_USE_SQLITE was only ever set as a
# temporary PowerShell session variable and never persisted to .env.
# Production (DEBUG=False) keeps requiring MySQL to be configured explicitly.
USE_SQLITE = _env_bool('DJANGO_USE_SQLITE', default=DEBUG)

if USE_SQLITE:
    if not DEBUG:
        raise ImproperlyConfigured('SQLite is restricted to development. Set DJANGO_USE_SQLITE=False in production.')
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'test.sqlite3',
        }
    }
else:
    required_database_values = {
        name: os.environ.get(name, '').strip()
        for name in ('DB_NAME', 'DB_USER', 'DB_PASSWORD')
    }
    missing_database_values = [name for name, value in required_database_values.items() if not value]
    if missing_database_values:
        raise ImproperlyConfigured(
            'MySQL is selected but required settings are missing: '
            + ', '.join(missing_database_values)
        )
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': required_database_values['DB_NAME'],
            'USER': required_database_values['DB_USER'],
            'PASSWORD': required_database_values['DB_PASSWORD'],
            'HOST': os.environ.get('DB_HOST', 'localhost'),
            'PORT': os.environ.get('DB_PORT', '3306'),
            'CONN_MAX_AGE': int(os.environ.get('DB_CONN_MAX_AGE', '60')),
            'CONN_HEALTH_CHECKS': True,
            'OPTIONS': {
                'charset': 'utf8mb4',
                'connect_timeout': int(os.environ.get('DB_CONNECT_TIMEOUT', '10')),
                'init_command': "SET sql_mode='STRICT_TRANS_TABLES'",
                'isolation_level': 'read committed',
            },
        }
    }
    database_ssl_ca = os.environ.get('DB_SSL_CA', '').strip()
    if database_ssl_ca:
        DATABASES['default']['OPTIONS']['ssl'] = {'ca': database_ssl_ca}


