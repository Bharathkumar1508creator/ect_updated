# DJANGO_USE_SQLITE accepts True/true/1/yes (case-insensitive). When it is
# not set at all, local development (DEBUG=True) defaults to SQLite instead
# of silently falling through to MySQL with a blank/wrong password — that
# silent fallback is what caused "Access denied for user 'root'@'localhost'
# (using password: NO)" after DJANGO_USE_SQLITE was only ever set as a
# temporary PowerShell session variable and never persisted to .env.
# Production (DEBUG=False) keeps requiring MySQL to be configured explicitly.
USE_SQLITE = _env_bool('DJANGO_USE_SQLITE', default=DEBUG)

if USE_SQLITE:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'test.sqlite3',
        }
    }
else:
    if 'DB_PASSWORD' not in os.environ:
        raise ImproperlyConfigured(
            'MySQL is selected (DJANGO_USE_SQLITE is not set) but DB_PASSWORD is '
            'missing from .env. Either add DB_NAME/DB_USER/DB_PASSWORD/DB_HOST/DB_PORT '
            'to .env, or set DJANGO_USE_SQLITE=True to use the local SQLite database.'
        )
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': os.environ.get('DB_NAME', 'ect_database'),
            'USER': os.environ.get('DB_USER', 'root'),
            'PASSWORD': os.environ.get('DB_PASSWORD', ''),
            'HOST': os.environ.get('DB_HOST', 'localhost'),
            'PORT': os.environ.get('DB_PORT', '3306'),
        }
    }


